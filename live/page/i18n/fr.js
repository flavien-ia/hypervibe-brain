const HELD_NOUNS = { conversations: ["conversation", "conversations", "e"], documents: ["document", "documents", ""] };
const heldNoun = (name) => /** @type {Record<string, string[] | undefined>} */ (HELD_NOUNS)[name] ?? ["élément", "éléments", ""];
const heldCount = (name, items) => `${number(items)} ${heldNoun(name)[items > 1 ? 1 : 0]}`;

const decimal = (n) => n.toLocaleString("fr-FR", { maximumFractionDigits: 1 });
/** "6 millions", "1,5 million", "850 000": French counts in the plural from two. */
const amount = (n) => {
  if (n < 1e6) return number(n >= 10_000 ? Math.round(n / 1000) * 1000 : n);
  const millions = n >= 1e7 ? Math.round(n / 1e6) : Math.round(n / 1e5) / 10;
  return `${decimal(millions)} million${millions >= 2 ? "s" : ""}`;
};
/** "6 millions de jetons", "850 000 jetons", "aucun jeton". (In French a token is a "jeton", everywhere on the page: decided on 2026-11-21.) */
const tokensWords = (n) => (!n ? "aucun jeton" : n >= 1e6 ? `${amount(n)} de jetons` : `${amount(n)} jeton${s(Math.round(n))}`);
const heldWhat = (name, items, estimate) => `${heldCount(name, items)}${estimate ? `, environ ${tokensWords(estimate)}` : ""}`;

